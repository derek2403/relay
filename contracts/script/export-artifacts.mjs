// Writes lib/relay/sessionMinter.ts (ABI, creation bytecode, Solidity source) from the Foundry
// build, so the app can deploy and call the SessionMinter with viem/wagmi.
//   cd contracts && forge build && node script/export-artifacts.mjs

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { keccak256, stringToHex } from "viem";

const contractsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceFile = "src/SessionMinter.sol";
const artifactFile = "out/SessionMinter.sol/SessionMinter.json";
const target = path.resolve(contractsDir, "../lib/relay/sessionMinter.ts");

const source = await fs.readFile(path.join(contractsDir, sourceFile), "utf8");
const artifact = JSON.parse(
  await fs.readFile(path.join(contractsDir, artifactFile), "utf8").catch(() => {
    throw new Error(`${artifactFile} not found: run "forge build" in contracts/ first`);
  }),
);

// Refuse to export bytecode compiled from an older version of the source.
const builtHash = artifact.metadata?.sources?.[sourceFile]?.keccak256;
if (builtHash !== keccak256(stringToHex(source))) {
  throw new Error(`${artifactFile} is stale: run "forge build" in contracts/ first`);
}

const bytecode = artifact.bytecode?.object;
if (!/^0x([0-9a-f]{2})+$/i.test(bytecode ?? "")) throw new Error(`no bytecode in ${artifactFile}`);

const solc = artifact.metadata?.compiler?.version ?? "unknown solc";
const header = [
  `// Generated by contracts/script/export-artifacts.mjs from contracts/${sourceFile} (solc ${solc}). Do not edit.`,
  "// Regenerate: cd contracts && forge build && node script/export-artifacts.mjs",
].join("\n");

await fs.writeFile(
  target,
  `${header}

export const SessionMinterAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const SessionMinterBytecode = "${bytecode}" as const;

export const SessionMinterSource = ${JSON.stringify(source)};
`,
);

console.log(`wrote ${path.relative(process.cwd(), target)} (${(bytecode.length - 2) / 2} bytes of bytecode)`);
