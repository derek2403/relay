// Writes lib/chain/artifacts.ts (ABI, creation bytecode and their hashes) for the Relay × MultiBaas
// contracts, from the Foundry build:
//   cd contracts && forge build && node script/export-chain-artifacts.mjs
//
// Hashes (so the relay can pin the approved escrow template and detect drift):
//   bytecodeHash = keccak256(creation bytecode bytes)
//   abiHash      = keccak256(utf8(canonical JSON of the ABI)), canonical = object keys sorted
//                  recursively, array order kept, no whitespace.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { keccak256, stringToHex } from "viem";

const contractsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.resolve(contractsDir, "../lib/chain/artifacts.ts");

const contracts = [
  { exportName: "RELAY_TOKEN", contractName: "RelayTestToken", label: "relay-token" },
  { exportName: "POLICY_VAULT", contractName: "PolicyVault", label: "relay-vault" },
  { exportName: "SIMPLE_ESCROW", contractName: "SimpleEscrow", label: "relay-escrow" },
];

/** JSON with object keys sorted recursively and no whitespace. */
function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value && typeof value === "object") {
    const keys = Object.keys(value).sort();
    return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

const blocks = [];
let solc = null;
for (const { exportName, contractName, label } of contracts) {
  const sourceFile = `src/${contractName}.sol`;
  const artifactFile = `out/${contractName}.sol/${contractName}.json`;
  const artifact = JSON.parse(
    await fs.readFile(path.join(contractsDir, artifactFile), "utf8").catch(() => {
      throw new Error(`${artifactFile} not found: run "forge build" in contracts/ first`);
    }),
  );

  // Refuse to export bytecode compiled from an older version of any source it was built from.
  for (const [file, info] of Object.entries(artifact.metadata?.sources ?? {})) {
    const source = await fs.readFile(path.join(contractsDir, file), "utf8").catch(() => null);
    if (source === null || info?.keccak256 !== keccak256(stringToHex(source))) {
      throw new Error(`${artifactFile} is stale (${file} changed): run "forge build" in contracts/ first`);
    }
  }

  const bytecode = artifact.bytecode?.object;
  if (!/^0x([0-9a-f]{2})+$/i.test(bytecode ?? "")) throw new Error(`no bytecode in ${artifactFile}`);
  if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) throw new Error(`no ABI in ${artifactFile}`);

  const version = artifact.metadata?.compiler?.version ?? "unknown";
  if (solc && solc !== version) throw new Error(`mixed compiler versions: ${solc} and ${version}`);
  solc = version;

  const bytecodeHash = keccak256(bytecode);
  const abiHash = keccak256(stringToHex(canonicalJson(artifact.abi)));
  blocks.push(`/** ${contractName} (${sourceFile}), uploaded to MultiBaas as "${label}". */
export const ${exportName} = {
  contractName: ${JSON.stringify(contractName)},
  label: ${JSON.stringify(label)},
  abi: ${JSON.stringify(artifact.abi, null, 2).replace(/\n/g, "\n  ")},
  bytecode: "${bytecode}",
  bytecodeHash: "${bytecodeHash}",
  abiHash: "${abiHash}",
} as const;`);
  console.log(`${contractName}: ${(bytecode.length - 2) / 2} bytes, bytecodeHash ${bytecodeHash}, abiHash ${abiHash}`);
}

const header = [
  `// Generated by contracts/script/export-chain-artifacts.mjs from contracts/src (solc ${solc}). Do not edit.`,
  "// Regenerate: cd contracts && forge build && node script/export-chain-artifacts.mjs",
  "// bytecodeHash = keccak256(bytecode); abiHash = keccak256(utf8(JSON of the ABI with object keys sorted",
  "// recursively, array order kept, no whitespace)).",
].join("\n");

await fs.mkdir(path.dirname(target), { recursive: true });
await fs.writeFile(
  target,
  `${header}

import type { Abi, Hex } from "viem";

/** One compiled contract as the relay uploads, deploys and pins it. */
export type ChainArtifact = {
  readonly contractName: string;
  readonly label: string;
  readonly abi: Abi;
  readonly bytecode: Hex;
  readonly bytecodeHash: Hex;
  readonly abiHash: Hex;
};

${blocks.join("\n\n")}

/** Every artifact, keyed by MultiBaas label. */
export const CHAIN_ARTIFACTS = {
  "relay-token": RELAY_TOKEN,
  "relay-vault": POLICY_VAULT,
  "relay-escrow": SIMPLE_ESCROW,
} as const satisfies Record<string, ChainArtifact>;
`,
);

console.log(`wrote ${path.relative(process.cwd(), target)}`);
